function aiRespond(text){
  const t=text.toLowerCase();
  let reply=null;
  const styleWords = {modern:'modern', luxury:'luxury', minimal:'minimal', premium:'premium', compact:'compact',
    contemporary:'contemporary', family:'family', open:'open', airy:'open', large:'family'};
  const roomWords = Object.fromEntries(ROOM_TYPES.map(r=>[r.label.toLowerCase(),r.key]).concat(
    [['bathroom','bathroom'],['living room','living'],['bedroom','bedroom'],['master bedroom','masterBedroom'],
     ['kitchen','kitchen'],['dining','dining'],['dining table','dining']]));

  // "give me a <style> <room>" / "make my <room> more <style>"
  let matchedRoom=null;
  for(const label in roomWords){ if(t.includes(label)){ matchedRoom=roomWords[label]; break; } }
  let matchedStyle=null;
  for(const w in styleWords){ if(t.includes(w)){ matchedStyle=styleWords[w]; break; } }

  if(matchedRoom && /add another|add a|add /.test(t) && t.includes('bedroom')){
    STATE.rooms.push(mkRoom('bedroom', 'Bedroom '+(STATE.rooms.filter(r=>r.type==='bedroom').length+2)));
    reply = `Added another bedroom to your plan — ${STATE.rooms.length} rooms total now. Open "Complete House" to assign it a design.`;
  } else if(matchedRoom && matchedStyle){
    const options = allDesignsFor(matchedRoom).filter(d=>d.style===matchedStyle || d.styleName.toLowerCase().includes(matchedStyle));
    const pick = options[0] || allDesignsFor(matchedRoom)[0];
    const room = STATE.rooms.find(r=>r.type===matchedRoom);
    if(room){ room.designId = pick.id; reply = `Done — set "${room.label}" to ${pick.name}. Check it in Complete House.`; }
    else { reply = `I found "${pick.name}" in the ${ROOM_BY_KEY[matchedRoom].label} library — open the Design Library to select it, since you don't have that room in your current plan yet.`; }
  } else if(matchedRoom && /larger|bigger|increase/.test(t)){
    const room = STATE.rooms.find(r=>r.type===matchedRoom);
    if(room){ room.length=Math.round(room.length*1.15); room.width=Math.round(room.width*1.15); room.area=room.length*room.width;
      reply = `Enlarged "${room.label}" to ${room.length}′ × ${room.width}′ (${room.area} sq ft).`; }
    else reply = `You don't have a ${ROOM_BY_KEY[matchedRoom].label} in the current plan yet.`;
  } else if(/wall color|change the wall|paint/.test(t)){
    reply = `Open any design's card → View → the wall-color swatches in the customize panel to repaint it — I've highlighted the Design Library for you.`;
  } else if(matchedRoom){
    reply = `Here's the ${ROOM_BY_KEY[matchedRoom].label} library — 10 designs, each with a 2D and 3D view.`;
  } else {
    reply = `I can switch a room's design by style ("make my living room more modern"), add rooms ("add another bedroom"), or resize a room ("make the kitchen larger"). Try one of those, or browse the Design Library directly.`;
  }
  renderSchedule && STATE.rooms.length && renderCompleteHouse();
  return reply;
}
