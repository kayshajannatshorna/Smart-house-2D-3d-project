  const L=design.length, W=design.width;
  const k = 210/(L+W);
  const ox = 40, oy = 60 + W*ISO.b*k;
  let s = `<svg viewBox="0 0 ${(L+W)*ISO.a*k+80} ${(L+W)*ISO.b*k+ (opts.wallH||9)*k + 90}" xmlns="http://www.w3.org/2000/svg" font-family="JetBrains Mono, monospace">`;
