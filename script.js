function computeLand(input){
  const totalArea = input.length*input.width;
  const setback = CONFIG.setbackFt;
  const netL = Math.max(input.length-2*setback,4);
  const netW = Math.max(input.width-2*setback,4);
  const setbackArea = totalArea - netL*netW;
  const buildableArea = round1(netL*netW*CONFIG.buildableRatio);
  const footprint = round1(Math.min(buildableArea, netL*netW));
  const openSpace = round1(totalArea-footprint);
  const suggestedFloorArea = round1(footprint*CONFIG.floorAreaEfficiency);
  return {totalArea:round1(totalArea), buildableArea, setbackArea:round1(setbackArea), footprint, openSpace, suggestedFloorArea, netL, netW};
}

function suggestFloorPlans(input, calc){
  const roomWanted = ['bedrooms','bathrooms','livingRoom','diningRoom','kitchen','drawingRoom','guestRoom','studyRoom']
    .reduce((s,k)=> s+(Number(input[k])||0), 0);
  const perFloorCapacity = Math.max(1, Math.floor(calc.suggestedFloorArea/(CONFIG.minRoomLen*CONFIG.minRoomWid)));
  const minFloorsNeeded = Math.max(1, Math.ceil(roomWanted/Math.max(perFloorCapacity,1)));
  const plans=[
    {id:'A', name:'Ground Floor', floors:1, desc:'Single-storey — fastest to build, best for smaller families or where fewer floors are preferred.'},
    {id:'B', name:'Ground + 1st Floor', floors:2, desc:'Balanced footprint and headroom — the common choice for the requirements you entered.'},
    {id:'C', name:'Ground + 1st + 2nd Floor', floors:3, desc:'Maximises room count on a smaller footprint, at higher construction cost.'}
  ];
  plans.forEach(p=>{
    p.roomsPerFloor = Math.ceil(roomWanted/p.floors);
    p.fits = p.floors>=Math.min(minFloorsNeeded,3);
    p.recommended = p.floors===clamp(minFloorsNeeded,1,3);
  });
  return {plans, minFloorsNeeded, roomWanted, perFloorCapacity};
}

const FLOOR_NAMES=['Ground','1st Floor','2nd Floor','3rd Floor'];
function buildRoomList(input, floors){
  const wanted = [
    ['bedrooms','bedroom','Bedroom'], ['bathrooms','bathroom','Bathroom'],
    ['livingRoom','living','Living Room'], ['diningRoom','dining','Dining Room'],
    ['kitchen','kitchen','Kitchen'], ['drawingRoom','drawing','Drawing Room'],
    ['guestRoom','guest','Guest Room'], ['studyRoom','study','Study Room'],
    ['balcony','balcony','Balcony'], ['parking','garage','Garage / Parking']
  ];
  const rooms=[];
  wanted.forEach(([field,typeKey,label])=>{
    let n=Number(input[field])||0;
    if(field==='bedrooms' && n>0){ // first bedroom becomes a Master Bedroom automatically
      rooms.push(mkRoom('masterBedroom','Master Bedroom'));
      n-=1;
    }
    for(let i=0;i<n;i++) rooms.push(mkRoom(typeKey, n>1? `${label} ${i+1}`:label));
  });
  // always include a staircase if more than one floor
  if(floors>1) rooms.push(mkRoom('staircase','Staircase'));
  // family-size aware extras
  if(Number(input.familySize)>5 && !wanted.some(([f])=>input[f])) rooms.push(mkRoom('family','Family Room'));
  // assign to floors round-robin, keeping ground floor priority for kitchen/living/parking/guest
  const groundFirst=['kitchen','living','drawing','dining','guest','garage','staircase'];
  let gi=0, oi=0;
  const perFloor = Math.max(1,Math.ceil(rooms.length/floors));
  const groundRooms = rooms.filter(r=>groundFirst.includes(r.type));
  const upperRooms = rooms.filter(r=>!groundFirst.includes(r.type));
  const assigned=[];
  groundRooms.forEach(r=>{ r.floor=0; assigned.push(r); });
  let f=floors>1?1:0, count=0;
  upperRooms.forEach(r=>{
    r.floor = floors>1 ? (1+ (count % (floors-1))) : 0;
    count++; assigned.push(r);
  });
  // if ground floor overloaded and upper floors exist, rebalance a little
  return assigned;
}
function mkRoom(typeKey,label){
  return {id:uid(), type:typeKey, label, length:CONFIG.minRoomLen, width:CONFIG.minRoomWid,
    area:CONFIG.minRoomLen*CONFIG.minRoomWid, floor:0, designId:null, overrides:{}};
}

