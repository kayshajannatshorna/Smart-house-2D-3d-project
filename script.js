/* ---------------------------------------------------------
   4. LAYOUT TRANSFORM — makes the 10 designs genuinely differ
   in arrangement, not just color. Applies mirroring, a90 clock
   shift and small deterministic jitter per design index.
--------------------------------------------------------- */
function transformFurniture(item, variant, rnd){
  let {x,y,rot}=item;
  if(variant%2===1){ x=1-x; rot=(360-rot)%360; } // mirror horizontally
  if(variant%5===4){ y=1-y; rot=(180-rot+360)%360; } // mirror vertically (space-saving/compact set)
  const jx=(rnd()-.5)*0.05, jy=(rnd()-.5)*0.05;
  x=clamp(x+jx,.04,.96); y=clamp(y+jy,.04,.96);
  return {x,y,rot};
}

/* ---------------------------------------------------------
   5. DESIGN GENERATOR — builds the 10 designs for a room type.
   Deterministic (seeded) so reloading gives the same catalog;
   admin-added custom designs are appended separately.
--------------------------------------------------------- */
const catalogCache = {};
function generateDesigns(typeKey){
  if(catalogCache[typeKey]) return catalogCache[typeKey];
  const rt = ROOM_BY_KEY[typeKey];
  const names = NAME_OVERRIDES[typeKey] || STYLE_PRESETS.map(p=>p.name);
  const tags  = NAME_OVERRIDES[typeKey+'Tags'] || STYLE_PRESETS.map(p=>p.tag);
  const list=[];
  for(let i=0;i<10;i++){
    const preset = STYLE_PRESETS[i];
    const rnd = seededRand(i+1 + typeKey.length*13);
    const tag = tags[i];
    const furniture = rt.furniture
      .filter(f=> f.tags.includes('*') || f.tags.includes(tag))
      .map(f=>{
        const t = transformFurniture(f, preset.variant, rnd);
        return Object.assign({}, f, t);
      });
    list.push({
      id: typeKey+'-'+i,
      roomType: typeKey,
      roomLabel: rt.label,
      index: i,
      name: (names[i]||preset.name)+' '+rt.label,
      style: tag,
      styleName: names[i]||preset.name,
      length: CONFIG.minRoomLen,
      width: CONFIG.minRoomWid,
      wallColor: WALL_COLORS[preset.wall].hex,
      wallColorName: WALL_COLORS[preset.wall].name,
      floorMaterial: FLOOR_MATERIALS[preset.floor].name,
      floorColor: FLOOR_MATERIALS[preset.floor].hex,
      accent: preset.accent,
      furniture,
      doors: rt.doors,
      windows: rt.windows,
      custom:false
    });
  }
  catalogCache[typeKey]=list;
  return list;
}
function allDesignsFor(typeKey){
  const base = generateDesigns(typeKey);
  const custom = STATE.customDesigns.filter(d=>d.roomType===typeKey);
  return base.concat(custom);
}
function findDesign(id){
  for(const rt of ROOM_TYPES){
    const d = allDesignsFor(rt.key).find(x=>x.id===id);
    if(d) return d;
  }
  return null;
}

